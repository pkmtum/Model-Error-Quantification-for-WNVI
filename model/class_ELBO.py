import torch
from model.ParentClasses.class_Priors_or_Posteriors_Handler import DistributionHandler


class ELBO:
    """Evidence Lower Bound (ELBO) calculation and closed form updates."""

    def __init__(
        self,
        posteriors: DistributionHandler,
        likelihoods: DistributionHandler,
        priors: DistributionHandler,
    ) -> None:
        self.posteriors = posteriors
        self.likelihoods = likelihoods
        self.priors = priors
        self.zero = torch.tensor(0.0)

    def sample(self, num_samples: int = 1):
        """Sample from the posterior distribution.

        Args:
            num_samples (int, optional): Number of samples to draw from the posterior. Defaults to 1.

        Returns:
            dict[str, torch.Tensor]: A dictionary containing the sampled variables.
        """
        return self.posteriors.sample(num_samples=num_samples)

    def eval(
        self, samples: dict[str, torch.Tensor]
    ) -> tuple[torch.Tensor, dict[str, torch.Tensor], dict[str, torch.Tensor], dict]:
        """Calculate the Evidence Lower Bound (ELBO) and its components. Performes also closed form updates of parameters
        Args:
            samples (dict[str, torch.Tensor]): Samples from the posterior distribution. Generated by posterior.sample(num_samples), can be called by ELBO.sample(num_samples).

        Returns:
            tuple[torch.Tensor, dict[str, torch.Tensor], dict[str, torch.Tensor], dict]: A tuple containing the ELBO, a dictionary of ELBO parts, a dictionary of samples, and a dictionary of intermediates.
        """
        # -------------------------------------------------------------
        # calculate the expected log likelihood
        E_log_likelihoods, _ = self.likelihoods.expected_log_prob(samples)
        summed_E_log_likelihoods = sum(E_log_likelihoods.values(), self.zero)
        # log prob of priors
        E_log_priors, _ = self.priors.expected_log_prob(samples)
        summed_E_log_priors = sum(E_log_priors.values(), self.zero)
        # entropy (of q)
        E_entropy_posteriors, _ = self.posteriors.expected_entropy(samples)
        summed_E_entropy_posteriors = sum(E_entropy_posteriors.values(), self.zero)
        # ELBO as the sum of all log probabilities
        elbo = (
            summed_E_log_likelihoods + summed_E_log_priors + summed_E_entropy_posteriors
        )

        return elbo, E_log_likelihoods, E_log_priors, E_entropy_posteriors

    def collect_intermediates(self) -> dict[str, torch.Tensor]:
        """Collect intermediates from the posterior, likelihoods, and priors.

        Returns:
            dict[str, torch.Tensor]: A dictionary containing the collected intermediates with their names defined in the distributions.
        """
        intermediates = dict()
        intermediates.update(self.posteriors.collect_intermediates())
        intermediates.update(self.likelihoods.collect_intermediates())
        intermediates.update(self.priors.collect_intermediates())
        return intermediates

    def closed_form_update(
        self, samples: dict[str, torch.Tensor], intermediates: dict[str, torch.Tensor]
    ) -> None:
        """Perform closed form updates of the posterior distribution.

        Args:
            samples (dict[str, torch.Tensor]): The sampled variables. Generated by posterior.sample(num_samples), can be called by ELBO.sample(num_samples).
            intermediates (dict[str, torch.Tensor]): The collected intermediate values. Generated by ELBO.collect_intermediates().
        """
        self.posteriors.closed_form_update(samples, intermediates)
